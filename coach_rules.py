def steps_for(run):
    genre = ""
    try:
        genre = run.get("genre") if hasattr(run, "get") else run["genre"]
    except Exception:
        genre = ""
    return NAR_STEPS if str(genre or "").strip() == "记叙文" else STEPS


def total_steps(run):
    return len(steps_for(run))


def step_messages(task, run, steps, step_no, submit_text):
    st = steps_for(run).get(step_no, steps_for(run)[1])
    prev = "\n\n".join(
        "【环节" + str(s["step"]) + "】\n学生交：" + (s["submit_text"] or "")[:800]
        + "\n教练诊断：" + (s["reply"] or "")[:800]
        for s in steps[-3:])
    user = (
        "【作文题目】" + task["title"] + "\n【题目材料/要求】" + task["prompt"] + "\n"
        + ("【引导语】" + task["guide"] + "\n" if task.get("guide") else "")
        + ("【主稿（一稿存档）】\n" + (run["draft"] or "")[:3000] + "\n" if run.get("draft") else "")
        + ("【此前环节记录】\n" + prev + "\n" if prev else "")
        + "【学生本次提交（环节" + str(step_no) + "：" + st["name"] + "）】\n" + submit_text + "\n\n"
        + "请按诊断四段输出本环节诊断，并在最后单独一行输出闸门 JSON：{\"gate\":\"pass\"} 或 {\"gate\":\"retry\"}。"
    )
    consts = NAR_CONSTITUTION if steps_for(run) is NAR_STEPS else CONSTITUTION
    sys = consts + "\n\n【本环节任务】" + st["task"]
    return [{"role": "system", "content": sys}, {"role": "user", "content": user}]


def report_messages(task, run, steps):
    detail = "\n\n".join(
        "【环节" + str(s["step"]) + "】\n学生交：" + (s["submit_text"] or "")[:600]
        + "\n诊断与处方：" + (s["reply"] or "")[:600]
        + "\n判定：" + str(s["gate"])
        for s in steps)
    consts = NAR_CONSTITUTION if steps_for(run) is NAR_STEPS else CONSTITUTION
    sys = consts + "\n\n学生已完成全部环节，现在生成结课双报告。"
    user = (
        "【作文题目】" + task["title"] + "：" + task["prompt"] + "\n【主稿】\n" + (run["draft"] or "")[:3000] + "\n"
        "【全程打磨记录】\n" + detail + "\n\n"
        "请输出两份报告，用分隔线隔开：\n"
        "一、《修改前后对照总报告》：逐环节列出“学生原来怎么写，改成什么样，为什么这么改”。\n"
        "二、《修改总结与进步对照报告》：总结该生最明显的三个进步、仍需注意的两个问题、下一步自主训练建议。\n"
        "两份报告都要具体引用学生原句做对照，不许空评。"
    )
    return [{"role": "system", "content": sys}, {"role": "user", "content": user}]



def steps_meta(run=None):
    """给前端的环节元数据：按当前 run 的体裁返回。"""
    steps = steps_for(run) if run else STEPS
    return [{"step": k, "name": v["name"], "submit_hint": v["submit_hint"],
             "pass_criteria": v["pass_criteria"]} for k, v in sorted(steps.items())]



def ask_messages(task, run, steps, question):
    """学生中途提问：只答疑，不做闸门判定，不推进环节。"""
    st = steps_for(run).get(run["step"], steps_for(run)[1])
    prev = "\n\n".join(
        "【环节" + str(s["step"]) + " · " + s.get("gate", "") + "】\n学生：" + (s["submit_text"] or "")[:500]
        + "\n教练：" + (s["reply"] or "")[:500]
        for s in steps[-3:])
    user = (
        "【作文题目】" + task["title"] + "：" + task["prompt"] + "\n"
        + ("【主稿】\n" + (run["draft"] or "")[:2000] + "\n" if run.get("draft") else "")
        + ("【近期打磨记录】\n" + prev + "\n" if prev else "")
        + "【学生提问】" + question + "\n\n"
        + "请直接回答学生的疑问（这是环节进行中的插问，不是提交）：结合当前环节讲清楚，"
        + "给出可操作的下一步；不要推进环节、不要输出闸门 JSON。控制在300字以内。"
    )
    consts = NAR_CONSTITUTION if steps_for(run) is NAR_STEPS else CONSTITUTION
    sys = consts + "\n\n【当前所处环节】" + st["name"] + "（回答要贴合本环节目标）"
    return [{"role": "system", "content": sys}, {"role": "user", "content": user}]
